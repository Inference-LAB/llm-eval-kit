"""
llm_eval_kit.criteria.completeness
==================================
Evaluates the completeness of an LLM response by decomposing the prompt into
sub-questions or aspects and checking semantic coverage of each aspect.
"""

import json
from pathlib import Path
import re
from sentence_transformers import SentenceTransformer, util

from llm_eval_kit.registry import register_criterion

_CONFIG_PATH = Path(__file__).parent / "completeness_config.json"

with open(_CONFIG_PATH, "r", encoding="utf-8") as f:
    _CONFIG = json.load(f)

MODEL_NAME: str = _CONFIG["model_name"]
COVERAGE_THRESHOLD: float = _CONFIG["coverage_threshold"]

_model: SentenceTransformer | None = None


def _get_model() -> SentenceTransformer:
    """
    Lazily initializes and returns the cached SentenceTransformer singleton model.

    Returns:
        SentenceTransformer: Cached embedding model instance loaded from MODEL_NAME.

    Known Limitations:
        - Loads the model onto CPU/GPU on first invocation.
        - Memory consumption corresponds to the underlying transformer model footprint (~80-120MB RAM).
    """
    global _model
    if _model is None:
        _model = SentenceTransformer(MODEL_NAME)
    return _model


_ASPECT_SPLIT_REGEX = re.compile(
    r"\?+|\n+|(?:\band\b)|(?:\bas well as\b)|(?:\bplus\b)|(?:\balso\b)|;|(?:\d+[\.\)]\s+)",
    re.IGNORECASE,
)
_RESPONSE_SPLIT_REGEX = re.compile(r"(?<=[.!?۔؟])\s+|\n+")


def _extract_aspects(prompt: str) -> list[str]:
    """
    Decomposes a user prompt into key thematic aspects using rule-based conjunction heuristics.

    Args:
        prompt (str): Raw prompt string to decompose.

    Returns:
        list[str]: Cleaned list of aspect strings. If decomposition yields no sub-parts,
            returns a single-item list with the normalized prompt.

    Known Limitations:
        - Uses rule-based heuristics (splitting on 'and', 'as well as', '?', newlines, semicolons, and list numbers).
        - Implicit multi-part requirements not separated by conjunctions may remain un-split.
    """
    parts = _ASPECT_SPLIT_REGEX.split(prompt.strip())
    aspects = []
    for part in parts:
        cleaned = part.strip(" ,.-:;?!'\"")
        if len(cleaned.split()) >= 2 or len(cleaned) >= 5:
            aspects.append(cleaned)

    return aspects if aspects else [prompt.strip()]


def _split_response_segments(text: str) -> list[str]:
    """
    Segments a response string into sentence and paragraph chunks for aspect matching.

    Args:
        text (str): Response text to segment.

    Returns:
        list[str]: List of non-empty text chunks.
    """
    parts = _RESPONSE_SPLIT_REGEX.split(text.strip())
    chunks = [p.strip() for p in parts if p.strip()]
    return chunks if chunks else [text.strip()]


@register_criterion("completeness")
def completeness(prompt: str, response: str, context: str = "", **kwargs) -> dict:
    """
    Evaluates what fraction of the requested aspects in the prompt are addressed in the response.

    Args:
        prompt (str): The original prompt containing information requests.
        response (str): The response generated by the model to evaluate. If empty or whitespace-only,
            evaluates to score 0.0.
        context (str, optional): Additional reference context. Unused by completeness. Defaults to "".
        **kwargs: Arbitrary keyword arguments for registry compatibility.

    Returns:
        dict: Evaluation result dictionary containing:
            - score (float): Fraction of prompt aspects covered in the response [0.0, 1.0].
            - explanation (str): Human-readable summary of covered vs total aspects.
            - covered_aspects (list[str]): List of prompt aspect strings that met the coverage threshold.
            - total_aspects (int): Total number of extracted prompt aspects evaluated.

    Known Limitations:
        - Aspect extraction is heuristic-based and may not capture complex implicit constraints.
        - Semantic coverage is thresholded (default 0.60); partial or shallow mentions may count as covered.
        - Does not verify factual accuracy of the information provided for each aspect.
    """
    if prompt is None or not prompt.strip():
        return {
            "score": 0.0,
            "explanation": "Empty prompt provided; completeness cannot be evaluated.",
            "covered_aspects": [],
            "total_aspects": 0,
        }

    aspects = _extract_aspects(prompt)

    if response is None or not response.strip():
        return {
            "score": 0.0,
            "explanation": f"Empty response covers 0 of {len(aspects)} requested aspects.",
            "covered_aspects": [],
            "total_aspects": len(aspects),
        }

    model = _get_model()
    aspect_embeddings = model.encode(aspects, convert_to_tensor=True)
    response_segments = _split_response_segments(response)
    response_segment_embeddings = model.encode(response_segments, convert_to_tensor=True)

    similarity_matrix = util.cos_sim(aspect_embeddings, response_segment_embeddings)

    covered_aspects = []
    for i, aspect in enumerate(aspects):
        max_sim = float(similarity_matrix[i].max())
        if max_sim >= COVERAGE_THRESHOLD:
            covered_aspects.append(aspect)

    score = len(covered_aspects) / len(aspects) if aspects else 0.0

    explanation = (
        f"Response covers {len(covered_aspects)} of {len(aspects)} key aspects requested in the prompt."
    )

    return {
        "score": round(score, 3),
        "explanation": explanation,
        "covered_aspects": covered_aspects,
        "total_aspects": len(aspects),
    }
