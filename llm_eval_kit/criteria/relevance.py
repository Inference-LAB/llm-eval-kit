"""
llm_eval_kit.criteria.relevance
===============================
Evaluates semantic relevance of an LLM response to the user's prompt
by computing sentence embedding cosine similarity.
"""

import json
from pathlib import Path
from sentence_transformers import SentenceTransformer, util

from llm_eval_kit.registry import register_criterion

_CONFIG_PATH = Path(__file__).parent / "relevance_config.json"

with open(_CONFIG_PATH, "r", encoding="utf-8") as f:
    _CONFIG = json.load(f)

MODEL_NAME: str = _CONFIG["model_name"]

_model: SentenceTransformer | None = None


def _get_model() -> SentenceTransformer:
    """
    Lazily initializes and returns the cached SentenceTransformer singleton model.

    Returns:
        SentenceTransformer: Cached embedding model instance loaded from MODEL_NAME.

    Known Limitations:
        - Loads the model onto CPU/GPU on first invocation.
        - Memory consumption corresponds to the underlying transformer model footprint (~80-120MB RAM).
    """
    global _model
    if _model is None:
        _model = SentenceTransformer(MODEL_NAME)
    return _model


@register_criterion("relevance")
def relevance(prompt: str, response: str, context: str = "", **kwargs) -> dict:
    """
    Evaluates whether an LLM response directly addresses the topic and intent of the prompt.

    Args:
        prompt (str): The original prompt submitted to the model.
        response (str): The response generated by the model to evaluate. If empty or whitespace-only,
            evaluates to score 0.0.
        context (str, optional): Additional reference context. Unused directly by relevance. Defaults to "".
        **kwargs: Arbitrary keyword arguments for registry compatibility.

    Returns:
        dict: Evaluation result dictionary containing:
            - score (float): Cosine similarity score in [0.0, 1.0] indicating semantic relevance.
            - explanation (str): Human-readable justification of the relevance score.

    Known Limitations:
        - Evaluates semantic topicality and alignment, not factual accuracy or completeness.
        - A response that is on-topic but contains incorrect claims will still receive a high relevance score.
        - Default model ('all-MiniLM-L6-v2') is English-optimized; cross-lingual prompt-response pairs
          may receive uncalibrated similarity scores.
    """
    if prompt is None or not prompt.strip():
        return {
            "score": 0.0,
            "explanation": "Empty prompt provided; relevance cannot be evaluated.",
        }

    if response is None or not response.strip():
        return {
            "score": 0.0,
            "explanation": "Empty response contains no relevant content to address prompt.",
        }

    model = _get_model()
    prompt_embedding = model.encode(prompt, convert_to_tensor=True)
    response_embedding = model.encode(response, convert_to_tensor=True)

    similarity = float(util.cos_sim(prompt_embedding, response_embedding)[0][0])
    score = max(0.0, min(1.0, similarity))

    if score >= 0.70:
        explanation = "Response is highly relevant and directly addresses the prompt topic."
    elif score >= 0.40:
        explanation = "Response is moderately relevant to the prompt topic."
    else:
        explanation = "Response has low semantic relevance to the prompt topic."

    return {
        "score": round(score, 3),
        "explanation": explanation,
    }
